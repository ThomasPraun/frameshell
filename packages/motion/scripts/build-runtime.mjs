// Bundles the motion runtime (src/index.ts + @frameshell/schema/motion) into one browser script and writes it,
// as a string, to plugins/hyperframes/src/motion-runtime.ts: the plugin ships it inside its own files (ADR 0008).
// Needs built packages (`tsc -b`). `--check` writes nothing and exits 1 when the committed file differs.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const entry = fileURLToPath(new URL("../src/index.ts", import.meta.url));
const target = fileURLToPath(new URL("../../../plugins/hyperframes/src/motion-runtime.ts", import.meta.url));

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  globalName: "FrameshellMotion",
  platform: "browser",
  target: "es2022",
  minifyWhitespace: true,
  minifySyntax: true,
  legalComments: "none",
  logLevel: "silent",
});
const version = /export const version = "([^"]+)"/.exec(readFileSync(entry, "utf8"))?.[1];
if (!version) throw new Error("packages/motion/src/index.ts has no `export const version`");
const script = `/* Frameshell motion runtime ${version} (ADR 0033), Apache-2.0. Generated, do not edit. */\n${result.outputFiles[0].text}`;

const file = `// Generated by \`pnpm gen:motion\` from packages/motion. Do not edit: edit the source and regenerate.

/** File name of the motion runtime inside a composition directory. */
export const MOTION_RUNTIME_FILE = "frameshell-motion.js";

/** Version of the bundled motion runtime (ADR 0033). */
export const MOTION_RUNTIME_VERSION = ${JSON.stringify(version)};

/** The motion runtime script: defines \`window.FrameshellMotion\` (\`bind\`, \`write\`, springs, eases, stagger). */
export const MOTION_RUNTIME = ${JSON.stringify(script)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // Missing counts as drift.
  }
  if (current !== file) {
    console.error("plugins/hyperframes/src/motion-runtime.ts is out of date: run `pnpm gen:motion` and commit it.");
    process.exit(1);
  }
} else {
  writeFileSync(target, file);
}
