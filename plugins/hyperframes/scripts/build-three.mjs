// Bundles the pinned `three` package plus the addons 3D templates use into one classic browser script that sets
// `window.THREE`, and writes it, as a string, to src/three-runtime.ts: the plugin ships it inside its own files and
// `hyperframes new --template <3D template>` copies it next to the composition (ADR 0042).
// `--check` writes nothing and exits 1 when the committed file differs.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const plugin = fileURLToPath(new URL("..", import.meta.url));
const target = join(plugin, "src", "three-runtime.ts");
const threeDir = join(plugin, "node_modules", "three");
const { version } = JSON.parse(readFileSync(join(threeDir, "package.json"), "utf8"));
const license = readFileSync(join(threeDir, "LICENSE"), "utf8").replace(/\r\n/g, "\n").trim();

// ADR 0042 decision 4: the whole namespace (any core class works in a template) plus these addons. No TTFLoader: it
// imports opentype.js from a CDN URL at run time.
const ADDONS = {
  RoomEnvironment: "three/addons/environments/RoomEnvironment.js",
  RoundedBoxGeometry: "three/addons/geometries/RoundedBoxGeometry.js",
  TextGeometry: "three/addons/geometries/TextGeometry.js",
  "FontLoader, Font": "three/addons/loaders/FontLoader.js",
  GLTFLoader: "three/addons/loaders/GLTFLoader.js",
};
const names = Object.keys(ADDONS).join(", ");
const entry = [
  `import * as THREE from "three";`,
  ...Object.entries(ADDONS).map(([imported, path]) => `import { ${imported} } from ${JSON.stringify(path)};`),
  `globalThis.THREE = Object.assign({}, THREE, { ${names} });`,
].join("\n");

const result = await build({
  stdin: { contents: entry, resolveDir: plugin, loader: "js" },
  bundle: true,
  write: false,
  metafile: true,
  format: "iife",
  platform: "browser",
  target: "chrome120",
  minify: true,
  legalComments: "none",
  logLevel: "silent",
});
const outside = Object.keys(result.metafile.inputs).filter((file) => file !== "<stdin>" && !/(^|\/)node_modules\/(\.pnpm\/three@[^/]+\/node_modules\/)?three\//.test(file));
if (outside.length > 0) throw new Error(`the three bundle must hold only the MIT \`three\` package, got ${outside.join(", ")}`);

const header = `/*! three.js ${version} for Frameshell (ADR 0042): the three namespace plus ${names}. Generated, do not edit.\n\n${license}\n*/`;
const script = `${header}\n${result.outputFiles[0].text}`;

const file = `// Generated by \`pnpm gen:three\` from the pinned \`three\` package. Do not edit: re-pin and regenerate (ADR 0042).

/** File name of the three.js bundle inside a 3D composition directory. */
export const THREE_RUNTIME_FILE = "frameshell-three.js";

/** Version of the bundled \`three\` package. */
export const THREE_VERSION = ${JSON.stringify(version)};

/** First line of a Frameshell three.js bundle of any version, capturing that version. */
export const THREE_HEADER = /^\\/\\*! three\\.js (\\d+)\\.(\\d+)\\.(\\d+) for Frameshell \\(ADR 0042\\)/;

/** The three.js bundle: a classic script that defines \`window.THREE\` (MIT notice in its header). */
export const THREE_RUNTIME = ${JSON.stringify(script)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // Missing counts as drift.
  }
  if (current !== file) {
    console.error("plugins/hyperframes/src/three-runtime.ts is out of date: run `pnpm gen:three` and commit it.");
    process.exit(1);
  }
} else {
  writeFileSync(target, file);
}
